"""Assemble a narrated walkthrough from actual UI captures; no browser simulation.
Requires Pillow, FFmpeg, and per-scene WAV files generated by narrate.ps1.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, ImageOps
import json, subprocess, shutil, wave, math

root=Path(__file__).resolve().parents[1]
out=root/'artifacts'/'walkthrough'
out.mkdir(parents=True,exist_ok=True)
scenes=json.loads((root/'docs'/'demo-scenes.json').read_text(encoding='utf-8'))
fontdir=Path('C:/Windows/Fonts')
def font(size,bold=False):
    return ImageFont.truetype(str(fontdir/('segoeuib.ttf' if bold else 'segoeui.ttf')),size)
ffmpeg=shutil.which('ffmpeg')
if not ffmpeg: raise SystemExit('FFmpeg is required')
clips=[]
for idx,scene in enumerate(scenes):
    im=Image.new('RGB',(1920,1080),'#20271f')
    draw=ImageDraw.Draw(im)
    for angle in range(0,360,45):
        rad=math.radians(angle)
        draw.line((80+5*math.cos(rad),70+5*math.sin(rad),80+15*math.cos(rad),70+15*math.sin(rad)),fill='#e88056',width=3)
    draw.text((105,47),'blastradius',font=font(35,True),fill='#f2f4e8')
    draw.text((62,185),scene['label'],font=font(16,True),fill='#d48b66')
    y=241
    for line in scene['title'].splitlines():
        # Fit the title within the 480px text column.
        fs=43
        while draw.textlength(line,font=font(fs,True))>435: fs-=1
        draw.text((62,y),line,font=font(fs,True),fill='#f3f4eb'); y+=66
    draw.line((62,y+25,405,y+25),fill='#4f5f43',width=2)
    y+=67
    for line in scene['detail'].splitlines():
        draw.text((62,y),line,font=font(19),fill='#b3c19f');y+=33
    draw.text((62,862),'GRAPH HACKS 2026',font=font(16,True),fill='#c5d4b0')
    draw.text((62,901),'FalkorDB · Team cloud9',font=font(17),fill='#8fa17e')
    screenshot=Image.open(root/'docs'/'screenshots'/scene['image']).convert('RGB')
    x1,y1,x2,y2=scene['crop'];x2=min(x2,screenshot.width);y2=min(y2,screenshot.height)
    screenshot=screenshot.crop((x1,y1,x2,y2))
    box=(1320,815)
    screenshot=ImageOps.contain(screenshot,box,Image.Resampling.LANCZOS)
    draw.rounded_rectangle((540,138,1860,953),radius=12,fill='#f7f8f3')
    im.paste(screenshot,(540+(box[0]-screenshot.width)//2,138+(box[1]-screenshot.height)//2))
    draw.text((550,83),'ACTUAL APP CAPTURE',font=font(16,True),fill='#c0cdb0')
    draw.text((550,982),'Synthetic data · '+scene.get('mode','Graph policy agent')+' · Captured-state walkthrough',font=font(17),fill='#9bab8a')
    draw.text((1810,982),f'{idx+1:02d}/{len(scenes):02d}',font=font(17),fill='#c9d6b7')
    # A progress indicator links the real app states.
    draw.rectangle((0,1072,int(1920*(idx+1)/len(scenes)),1080),fill='#e86239')
    frame=out/f'scene-{idx}.png';im.save(frame)
    audio=out/f'voice-{idx}.wav'
    with wave.open(str(audio),'rb') as f: duration=f.getnframes()/f.getframerate()+.7
    clip=out/f'clip-{idx}.mp4'
    subprocess.run([ffmpeg,'-hide_banner','-loglevel','error','-y','-loop','1','-i',str(frame),'-i',str(audio),'-t',str(duration),'-vf','fps=24,format=yuv420p','-af','apad','-c:v','libx264','-preset','fast','-crf','21','-c:a','aac','-b:a','128k','-movflags','+faststart',str(clip)],check=True)
    clips.append(clip)
concat=out/'clips.txt'
concat.write_text(''.join("file '"+str(p).replace('\\','/')+"'\n" for p in clips),encoding='utf-8')
target=root/'artifacts'/'BlastRadius-walkthrough.mp4'
subprocess.run([ffmpeg,'-hide_banner','-loglevel','error','-y','-f','concat','-safe','0','-i',str(concat),'-c','copy','-movflags','+faststart',str(target)],check=True)
print(target)
